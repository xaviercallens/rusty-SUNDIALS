//! Direct numeric cross-check against the Python reference `quantumfluids.kinetic.vlasov`, on a
//! small deterministic 8x12 grid with a fixed field (`|linspace(-1, 1, 96)| + 0.1`, reshaped
//! row-major, exactly as numpy's default `.reshape` would lay it out) -- generated once and
//! pasted here as data, so this test does not depend on Python being installed. It complements
//! the physics tests in `src/lib.rs` (Landau damping rate, plasma echo) with an exact-value check
//! that every building block (`density`, `field_from`, `advect_x`, `advect_v`, `step`, `energy`,
//! `mass`) computes the same numbers as the Python original on the same input.
//!
//! `advect_v` and `step` are the exceptions: since this crate's natural cubic spline is not
//! scipy's not-a-knot (see the module docs in `src/lib.rs`), `advect_v`'s domain-edge cells
//! (queries shifted out of `[-vmax, vmax]`, where both implementations return exactly `0.0`) are
//! checked exactly and everything else to `1e-9`; `step` (which interpolates a different,
//! half-x-advected field, so the edge-sensitive cells move) is checked to `1e-3` everywhere,
//! comfortably separating the ~`4e-5` spline-boundary disagreement actually observed from what a
//! real bug would look like.

use qf_vlasov1d::{Grid, advect_v, advect_x, density, energy, field_from, mass, step};

fn f0() -> Vec<f64> {
    (0..96)
        .map(|idx| (-1.0 + 2.0 * idx as f64 / 95.0).abs() + 0.1)
        .collect()
}

fn grid() -> Grid {
    let k = 0.5f64;
    Grid::new(2.0 * std::f64::consts::PI / k, 8, 12, 3.0)
}

fn assert_close(label: &str, got: &[f64], want: &[f64], tol: f64) {
    for (i, (&g, &w)) in got.iter().zip(want).enumerate() {
        let diff = (g - w).abs() / w.abs().max(1e-12);
        assert!(
            diff < tol,
            "{label}[{i}]: got {g}, want {w}, rel diff {diff:.3e}"
        );
    }
}

#[test]
fn density_matches_python() {
    let want = [
        5.905263157894737,
        4.389473684210526,
        2.873684210526316,
        1.3578947368421055,
        1.3578947368421048,
        2.873684210526315,
        4.389473684210525,
        5.905263157894736,
    ];
    assert_close("density", &density(&f0(), &grid()), &want, 1e-12);
}

#[test]
fn field_from_matches_python() {
    let want = [
        -1.9343631788191267,
        -4.373989515532992,
        -4.373989515532992,
        -1.9343631788191291,
        1.9343631788191262,
        4.373989515532992,
        4.373989515532992,
        1.9343631788191296,
    ];
    assert_close("field_from", &field_from(&f0(), &grid()), &want, 1e-10);
}

#[test]
fn advect_x_matches_python() {
    let want: Vec<f64> = PYTHON_ADVECT_X.to_vec();
    assert_close("advect_x", &advect_x(&f0(), &grid(), 0.05), &want, 1e-9);
}

#[test]
fn advect_v_matches_python_away_from_the_boundary_spline() {
    let g = grid();
    let e = field_from(&f0(), &g);
    let got = advect_v(&f0(), &g, &e, 0.05);
    // Every 12th entry (j=0, the first velocity cell of each x-row) is a boundary case where
    // this crate's natural spline and scipy's not-a-knot can disagree more than round-off;
    // Python returns exactly 0.0 there (query point shifted out of range), and so does this
    // crate -- check those separately with an exact match, everything else to 1e-9.
    for (i, (&g_, &w)) in got.iter().zip(PYTHON_ADVECT_V.iter()).enumerate() {
        if w == 0.0 {
            assert_eq!(g_, 0.0, "index {i} should be exactly 0.0 (out of range)");
        } else {
            let diff = (g_ - w).abs() / w.abs();
            assert!(
                diff < 1e-9,
                "advect_v[{i}]: got {g_}, want {w}, rel diff {diff:.3e}"
            );
        }
    }
}

#[test]
fn step_matches_python() {
    let out = step(&f0(), &grid(), 0.05, true);
    // step composes advect_x (exact, checked to 1e-9 above) with advect_v (the spline-boundary
    // difference noted at the top of this file). Because step's v-advection interpolates the
    // *half-x-advected* field, not f0 directly, the specific (i, j) that land near the domain
    // edge differ from advect_v_matches_python_away_from_the_boundary_spline's isolated case
    // above, so this checks every entry at one looser-but-still-meaningful tolerance instead of
    // hand-picking boundary indices. 1e-3 comfortably separates "expected spline-boundary
    // disagreement" (measured here at ~4e-5) from a real bug (which would show as O(1) or larger).
    for (i, (&g, &w)) in out.iter().zip(PYTHON_STEP.iter()).enumerate() {
        let diff = (g - w).abs() / w.abs().max(1e-6);
        assert!(
            diff < 1e-3,
            "step[{i}]: got {g}, want {w}, rel diff {diff:.3e}"
        );
    }
}

#[test]
fn energy_and_mass_match_python() {
    let f = f0();
    let g = grid();
    assert!((energy(&f, &g) - 139.83763940840896).abs() / 139.83763940840896 < 1e-10);
    assert!((mass(&f, &g) - 45.635766967935936).abs() / 45.635766967935936 < 1e-10);
}

